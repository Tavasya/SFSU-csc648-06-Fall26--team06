-- 3D room scans (used by /rooms/[roomId]/3d, the Campus Map and the event page).
-- The rooms table, its storage bucket and policies were first created in the
-- Supabase dashboard; this migration records them in the repo.
-- Safe to re-run: every statement skips or replaces what already exists.

-- Rooms with a 3D scan. model_view_path is the .glb file in the "rooms" storage bucket.
create table if not exists public.rooms (
  id bigint generated by default as identity primary key,
  room_name character varying,
  has_3d_view boolean,
  model_view_path character varying,
  scan_date date
);

-- Each room belongs to a location (building, venue or outdoor space), so the
-- Campus Map and event pages know which building has a 3D scan.
alter table public.rooms add column if not exists location_id uuid references public.locations(id);
create index if not exists rooms_location_idx on public.rooms(location_id);

-- Everyone (signed out = anon, signed in = authenticated) can read rooms; nobody
-- can change them through the website. Both the permission (grant) and the row
-- policy are needed: Supabase checks the grant first, then the policy.
alter table public.rooms enable row level security;
revoke truncate, references, trigger on public.rooms from anon, authenticated;
grant select on public.rooms to anon, authenticated;
drop policy if exists "Public can read rooms" on public.rooms;
create policy "Public can read rooms" on public.rooms for select to anon, authenticated using (true);

-- Storage bucket for the .glb scan files, readable by everyone.
insert into storage.buckets(id, name, public) values ('rooms', 'rooms', true) on conflict (id) do nothing;
drop policy if exists "Read room models" on storage.objects;
create policy "Read room models" on storage.objects for select to public using (bucket_id = 'rooms');

-- The first scan: Rigoberta Menchu Hall (floor 1) is inside the Cesar Chavez Student Center.
insert into public.rooms(id, room_name, has_3d_view, model_view_path, scan_date)
overriding system value
values (1, 'Rigoberta Menchu Hall Floor 1', true, 'cesar_rigoberta_menchu_hall_f1.glb', '2026-10-04')
on conflict (id) do nothing;
update public.rooms
set location_id = (select id from public.locations where building_name = 'Cesar Chavez Student Center')
where id = 1 and location_id is null;
-- Keep the automatic numbering ahead of the row inserted above.
select setval(pg_get_serial_sequence('public.rooms', 'id'), greatest((select max(id) from public.rooms), 1));

